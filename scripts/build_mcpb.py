def write_manifest(stage: Path, version: str, target: Target) -> None:
    (stage / "manifest.json").write_text(
        json.dumps(manifest(version, target), indent=2, ensure_ascii=False) + "\n"
    )
    shutil.copy2(ICON, stage / "icon.png")


def pack(stage: Path, out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.unlink(missing_ok=True)
    _run([_which("npx"), "--yes", MCPB_PACKER, "pack", str(stage), str(out)])


def audit(stage: Path, out: Path, target: Target) -> None:
    """Fail on the packing regressions that only show up on a user's machine."""
    with zipfile.ZipFile(out) as zf:
        names = set(zf.namelist())
        unpacked = sum(i.file_size for i in zf.infolist())
    expected = {
        "manifest.json",
        "icon.png",
        f"server/python/{target.interpreter}",
        "server/lib/sitecustomize.py",
        "server/lib/anafpy/__init__.py",
    }
    if missing := sorted(expected - names):
        raise SystemExit(f"packed archive is missing {missing}")
    # mcpb pack silently drops .env* at any depth and materialises symlinks
    # into full copies. The stage has neither (assert, don't hope): nothing
    # dotfile-shaped goes in, and prune_runtime removed every link — so the
    # unpacked size must track the staged size.
    staged_files = [p for p in stage.rglob("*") if p.is_file()]
    if links := [p for p in staged_files if p.is_symlink()]:
        raise SystemExit(f"stage still contains symlinks: {links[:5]}")
    staged = sum(p.stat().st_size for p in staged_files)
    if unpacked > staged * 1.05 + 1_000_000:
        raise SystemExit(
            f"packed contents ({unpacked:,} B) outgrew the stage ({staged:,} B) "
            "— mcpb pack most likely materialised a symlink into a full copy"
        )
    print(
        f"{out.name}: {out.stat().st_size:,} B packed, {unpacked:,} B unpacked, "
        f"{len(names)} files"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--target",
        choices=("darwin-arm64", "darwin-x64", "win32-x64"),
        # No default=host_target() here: that would refuse to even parse args
        # on a host with no target of its own (the Linux CI runner, which only
        # ever uses --manifests-only).
        default=None,
        help="bundle target; defaults to (and must equal) the host's own",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=ROOT / "mcpb-dist",
        help="where the packed .mcpb lands (default: mcpb-dist/)",
    )
    parser.add_argument(
        "--manifests-only",
        type=Path,
        metavar="DIR",
        help="write every target's generated manifest into DIR/<target>/"
        "manifest.json and exit. Manifest generation is pure — no native "
        "host, no uv — so CI schema-validates all three from one runner.",
    )
    args = parser.parse_args()

    version, pin = read_pins()
    minor = pin.rsplit(".", 1)[0]
    targets = _targets(minor)

    if args.manifests_only is not None:
        for target in targets.values():
            target_dir = args.manifests_only / target.name
            target_dir.mkdir(parents=True, exist_ok=True)
            (target_dir / "manifest.json").write_text(
                json.dumps(manifest(version, target), indent=2, ensure_ascii=False)
                + "\n"
            )
            # The validator resolves the manifest's icon path — ship it too.
            shutil.copy2(ICON, target_dir / "icon.png")
            print("wrote", target_dir / "manifest.json")
        return

    target = targets[args.target or host_target()]
    require_native(target.name)
    uv = _which("uv")

    build_dir = ROOT / "build" / "mcpb" / target.name
    stage = build_dir / "stage"
    shutil.rmtree(stage, ignore_errors=True)
    stage.mkdir(parents=True)

    interpreter = stage_runtime(uv, pin, stage, target)
    prune_runtime(stage / "server" / "python", target)
    install_closure(uv, interpreter, stage / "server" / "lib", build_dir, target)
    write_manifest(stage, version, target)

    out = args.out_dir / f"anafpy-{target.name}.mcpb"
    pack(stage, out)
    audit(stage, out, target)


if __name__ == "__main__":
    main()
